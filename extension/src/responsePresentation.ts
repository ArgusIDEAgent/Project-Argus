import { randomBytes } from 'node:crypto';

export type SourceProof = {
  repository_id: string; snapshot_id: string; index_snapshot_id: string; evidence_id: string;
  file_id: string; symbol_id: string | null; file_path: string; start_line: number; end_line: number;
  source_hash: string; source_origin: string; schema_version: number;
};
export type BackendCitation = { reference: string; record_id: string; source: SourceProof };
export type SourceDisplay = { citation: BackendCitation; state: string; reason: string };
type Item = { item_id: string; text: string; origin: string; classification: string; authoritative: boolean;
  citation_ids: string[]; details: string[]; limitations: string[] };
type Requirement = { requirement_id: string; order: number; title: string; state: string;
  original: { intent: string; depends_on: number[] }; supporting_requirement_ids: string[];
  target_context?: string[];
  sections: { title: string; item_ids: string[] }[]; limitations: string[]; hidden_items: number;
  operations: { operation_id: string; execution_status: string; coverage_state: string; limitations: string[] }[] };
export type FollowUpDisplay = { requirement_id: string; label: string; prompt: string | null;
  mode: string; citation_id: string | null };
export type ResponsePresentation = { schema_version: 'phase9-1'; presentation_id: string;
  package_id: string; query_id: string; support_query_id: string; repository_id: string; snapshot_id: string;
  depth: 'quick' | 'standard' | 'deep'; status: string; items: Record<string, Item>;
  requirements: Requirement[]; sources: Record<string, SourceDisplay>; limitations: string[];
  model_status: string | null; fallback_status: string | null; follow_ups: FollowUpDisplay[];
  clarifications: { requirement_id: string; reason: string; truncated: boolean;
    candidates: { name: string; file_path: string | null; entity_id: string }[] }[] };

export function escapeDisplay(value: unknown): string {
  return String(value).replace(/[&<>"']/g, character => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[character]!));
}

const STATES: Record<string, string> = {
  success: 'Complete result', satisfied: 'Satisfied', addressed: 'Addressed',
  partial: 'Partial coverage', partially_satisfied: 'Partial coverage', ambiguous: 'Ambiguous target — clarification required',
  not_found: 'No verified match within scope/bounds', unsupported: 'Unsupported capability',
  stale: 'Stale source — historical evidence only', stale_index: 'Stale source — historical evidence only',
  error: 'Failed operation/result', skipped: 'Skipped dependency', deferred: 'Deferred requirement',
};
const CLASSES: Record<string, string> = {
  verified_source_observation: 'Indexed source observation', verified_graph_relationship: 'Verified static graph relationship',
  derived_analysis: 'Deterministic static analysis', hypothetical_consequence: 'HYPOTHESIS — not a verified outcome',
  unresolved_assertion: 'UNRESOLVED — not a verified relationship', model_interpretation: 'Model interpretation — not fact-checked',
  unknown: 'UNKNOWN — unsupported conclusion',
};
const e = escapeDisplay;

// Only opaque action keys generated by the extension host appear on controls.
export function renderResponseBody(view: ResponsePresentation, sourceKeys: Record<string, string> = {}, followUpKeys: Record<number, string> = {}, mode: 'preview' | 'hybrid' = 'preview', idPrefix = ''): string {
  const references = Object.keys(view.sources).sort();
  const number = (reference: string) => references.indexOf(reference) + 1;
  const list = (values: string[]) => values.length ? '<ul>' + values.map(value => '<li>' + e(value) + '</li>').join('') + '</ul>' : '';
  let body = '<header><h1>' + (mode === 'hybrid' ? 'CodeMind Hybrid Answer' : 'CodeMind Response Preview') + '</h1><p>' + e(STATES[view.status] || view.status) +
    ' · ' + e(view.depth) + ' · repository ' + e(view.repository_id) + ' · generation ' + e(view.snapshot_id) + '</p>';
  body += mode === 'hybrid' ? '<p>Evidence-grounded development mode. Citations verify provenance, not arbitrary explanatory prose.</p>' : '<p>Separate preview of supplied backend results. Source verification does not authenticate arbitrary prose.</p>';
  body += '<p>Query ' + e(view.query_id) + ' · supporting query ' + e(view.support_query_id) + '</p>';
  body += '<nav aria-label="Answer depth">' + ['quick', 'standard', 'deep'].map(depth => '<button type="button" data-depth="' + depth + '"' + (depth === view.depth ? ' disabled' : '') + '>' + e(depth) + '</button>').join('') + '</nav>';
  if (view.model_status !== null) body += '<p>Local model: ' + e(view.model_status) + ' · fallback: ' + e(view.fallback_status) + '</p>';
  body += '</header>';
  for (const requirement of view.requirements) {
    body += '<section class="requirement"><h2>' + e(requirement.order + 1) + '. ' + e(requirement.title) + '</h2>' +
      '<p class="coverage">' + e(STATES[requirement.state] || requirement.state) + ' · ' + e(requirement.requirement_id) + ' · ' + e(requirement.original.intent) + '</p>';
    if (requirement.target_context?.length) body += '<p>Supplied target/support scope (not navigation authority): ' + e(requirement.target_context.join('; ')) + '</p>';
    if (requirement.original.depends_on.length) body += '<p>Target dependencies: ' + e(requirement.original.depends_on.map(order => order + 1).join(', ')) + '</p>';
    if (view.depth === 'deep') body += '<p>Supporting requirements: ' + e(requirement.supporting_requirement_ids.join(', ')) + '</p>';
    for (const section of requirement.sections) {
      body += '<h3>' + e(section.title) + '</h3>';
      if (!section.item_ids.length) body += '<p>No accepted display findings for this requirement.</p>';
      for (const key of section.item_ids) {
        const item = view.items[key];
        if (!item) continue;
        body += '<article><p class="classification">' + e(CLASSES[item.classification] || item.classification) +
          (item.authoritative ? ' — within its recorded static/source scope' : ' — NON-AUTHORITATIVE') + '</p><p class="claim">' + e(item.text) + '</p>';
        if (item.details.length) body += '<pre>' + e(item.details.join('\n')) + '</pre>';
        if (item.citation_ids.length) body += '<p>Sources: ' + item.citation_ids.map(reference => '<a href="#' + e(idPrefix) + 'source-' + number(reference) + '">[' + number(reference) + ']</a>').join(' ') + '</p>';
        body += list(item.limitations) + '</article>';
      }
    }
    for (const operation of requirement.operations) {
      if (view.depth === 'quick' && operation.coverage_state === 'satisfied') continue;
      body += '<p>Operation ' + e(operation.operation_id) + ': execution ' + e(operation.execution_status) + '; coverage ' + e(STATES[operation.coverage_state] || operation.coverage_state) + '</p>' + list(operation.limitations);
    }
    body += '<h3>Coverage and uncertainty</h3>' + list(requirement.limitations) + '</section>';
  }
  if (view.clarifications.length) {
    body += '<section><h2>Clarification required — no target selected</h2>';
    for (const clarification of view.clarifications) {
      body += '<p>' + e(clarification.requirement_id + ': ' + clarification.reason) + '</p>' + list(clarification.candidates.map(candidate => candidate.name + ' · ' + (candidate.file_path || 'structural metadata') + ' · ' + candidate.entity_id));
      if (clarification.truncated) body += '<p>Candidate list is truncated.</p>';
    }
    body += '</section>';
  }
  body += '<section><h2>Sources (shared references)</h2>';
  for (const reference of references) {
    const source = view.sources[reference];
    const proof = source.citation.source;
    const label = '[' + number(reference) + '] ' + proof.file_path + ':' + proof.start_line + '-' + proof.end_line;
    const key = sourceKeys[reference];
    body += '<p id="' + e(idPrefix) + 'source-' + number(reference) + '">';
    body += source.state === 'verified' && key ? '<button type="button" data-source-key="' + e(key) + '">' + e(label) + '</button>' : '<span class="unavailable">' + e(label) + ' — ' + e(source.state) + ' (not navigable)</span>';
    body += '<small> ' + e(source.reason) + '</small></p>';
  }
  body += '</section><section><h2>Next investigations (never run automatically)</h2>';
  view.follow_ups.forEach((followUp, index) => {
    const key = followUpKeys[index];
    if (followUp.mode === 'copy_query' && key) body += '<p><button type="button" data-follow-up-key="' + e(key) + '">Copy query: ' + e(followUp.label) + '</button><code>' + e(followUp.prompt) + '</code></p>';
    else if (followUp.citation_id) body += '<p>' + e(followUp.label) + ': see source [' + number(followUp.citation_id) + '].</p>';
  });
  return body + '</section><section><h2>Analysis limitations</h2>' + list(view.limitations) + '</section><p id="' + e(idPrefix) + 'preview-error" role="alert"></p>';
}

export function responsePreviewHtml(view: ResponsePresentation, sourceKeys: Record<string, string>, followUpKeys: Record<number, string>): string {
  const nonce = randomBytes(16).toString('base64');
  return `<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'nonce-${nonce}'; script-src 'nonce-${nonce}';">
<title>CodeMind Response Preview</title><style nonce="${nonce}">
body { color:var(--vscode-foreground); background:var(--vscode-editor-background); font-family:var(--vscode-font-family); padding:20px; line-height:1.5; }
h1 { font-size:20px; } h2 { font-size:17px; } h3 { font-size:14px; } section { border-top:1px solid var(--vscode-panel-border); margin-top:20px; }
article { border-left:3px solid var(--vscode-panel-border); padding:0 12px; } p,li,pre,code { overflow-wrap:anywhere; white-space:pre-wrap; }
.classification,.coverage,.unavailable { color:var(--vscode-descriptionForeground); } button { color:var(--vscode-button-foreground); background:var(--vscode-button-background); border:0; padding:6px 10px; margin:4px; cursor:pointer; }
button:disabled { opacity:.6; cursor:default; } a { color:var(--vscode-textLink-foreground); } pre { padding:8px; background:var(--vscode-textCodeBlock-background); } small { font-size:11px; }
</style></head><body>${renderResponseBody(view, sourceKeys, followUpKeys)}<script nonce="${nonce}">
const api = acquireVsCodeApi();
document.addEventListener('click', event => {
  const control = event.target.closest('button'); if (!control) return;
  if (control.dataset.sourceKey) api.postMessage({ type:'previewSource', key:control.dataset.sourceKey });
  if (control.dataset.followUpKey) api.postMessage({ type:'previewCopyQuery', key:control.dataset.followUpKey });
  if (control.dataset.depth) api.postMessage({ type:'previewDepth', depth:control.dataset.depth });
});
window.addEventListener('message', event => {
  if (event.data && event.data.type === 'previewError') document.getElementById('preview-error').textContent = event.data.text;
});
</script></body></html>`;
}
